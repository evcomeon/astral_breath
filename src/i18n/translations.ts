export function getTranslation(lang: 'zh-CN' | 'en-US', key: string, params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations['zh-CN'];
  let text = (dict as Record<string, string>)[key] || (translations['zh-CN'] as Record<string, string>)[key] || key;

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}
